export function useTranslation(lang: 'vi' | 'en') {
  return (key: keyof typeof translations['vi'], replacements?: Record<string, string | number>): string => {
    const dict = translations[lang] || translations['vi'];
    let val = (dict[key] || translations['vi'][key] || key) as string;

    if (replacements) {
      Object.entries(replacements).forEach(([k, v]) => {
        val = val.replace(`{${k}}`, String(v));
      });
    }

    return val;
  };
}
